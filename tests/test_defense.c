    CHECK(!CopydogDefenseDue(900,950,337,512,0,50));
    CHECK(CopydogDefenseDue(900,950,338,512,0,50));
    CHECK(CopydogDefenseDue(900,950,726,512,0,50));
    CHECK(!CopydogDefenseDue(900,950,727,512,0,50));
    CHECK(!CopydogDefenseDue(-1,-1,0,512,0,0));
    CopydogDefenseObserve(&t,1,0,100,25034000,1,1000);
    CHECK(!CopydogDefenseBusy(&t));
    CHECK(CopydogDefenseBegin(&t,1,2,25034000,0,100,DEF_PARRY,20080000,1000));
    CHECK(t.phase==DEF_WAIT_ANIMATION&&t.confirmations==0);
    CHECK(!CopydogDefenseBegin(&t,1,2,25034000,0,100,DEF_ROLL,0,1001));
    CopydogDefenseObserve(&t,1,0,100,25034000,1,1100);
    CHECK(t.phase==DEF_WAIT_ANIMATION);
    CopydogDefenseObserve(&t,1,48032100,100,25034000,0,1154);
    CHECK(t.phase==DEF_WAIT_ANIMATION&&t.confirmations==0);
    CopydogDefenseObserve(&t,1,48032100,100,25034000,0,1166);
    CHECK(t.phase==DEF_ACTIVE&&t.delayMs==154&&t.confirmations==1);
    CopydogDefenseObserve(&t,1,48032110,100,6000,0,1200);
    CHECK(t.confirmations==1);
    CopydogDefenseObserve(&t,1,0,100,6000,1,1500);
    CopydogDefenseObserve(&t,1,0,100,6000,1,1512);
    CHECK(!CopydogDefenseBusy(&t));
    CHECK(CopydogDefenseBegin(&t,1,2,25034010,0,100,DEF_ROLL,6020000,1600));
    CopydogDefenseObserve(&t,1,27100,100,25034010,0,1620);
    CopydogDefenseObserve(&t,1,27100,100,25034010,0,1632);
    CHECK(t.phase==DEF_ACTIVE&&t.delayMs==20&&t.delayKind==DEF_ROLL);
    CopydogDefenseObserve(&t,1,5202,80,25034010,0,1700);
    CHECK(t.phase==DEF_CANCELLED&&t.reason==DEF_DAMAGE);
    CopydogDefenseObserve(&t,1,5202,80,25034010,0,1710);
    CHECK(CopydogDefenseBusy(&t));
    CopydogDefenseObserve(&t,1,5202,80,25034010,0,1722);
    CHECK(!CopydogDefenseBusy(&t));
    CHECK(CopydogDefenseBegin(&t,1,2,25034000,0,80,DEF_PARRY,11010000,2200));
    CopydogDefenseObserve(&t,1,42036900,80,25034000,1,2300);
    CopydogDefenseObserve(&t,1,42036900,80,25034000,1,2312);
    CHECK(t.phase==DEF_ACTIVE&&t.confirmations==3&&t.delayMs==100);
    CopydogDefenseObserve(&t,1,0,80,25034000,1,2700);
    CopydogDefenseObserve(&t,1,0,80,25034000,1,2712);
    CHECK(CopydogDefenseBegin(&t,1,2,25034000,0,80,DEF_PARRY,11010000,2800));
    CopydogDefenseObserve(&t,1,0,80,25034010,1,2810);
    CHECK(t.phase==DEF_WAIT_ANIMATION);
    CopydogDefenseObserve(&t,1,0,80,25034010,1,2822);
    CHECK(t.reason==DEF_TARGET_CHANGED);
    CopydogDefenseObserve(&t,1,0,80,25034000,1,3222);
    CopydogDefenseObserve(&t,1,0,80,25034000,1,3234);
    CHECK(CopydogDefenseBegin(&t,1,0,-1,0,80,DEF_ROLL,0,3300));
    CopydogDefenseObserve(&t,1,0,80,-1,1,3701);
